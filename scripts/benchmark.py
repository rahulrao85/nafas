"""Run the labelled benchmark and write docs/BENCHMARK_RESULTS.md.

    python scripts/benchmark.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
try:
    sys.stdout.reconfigure(encoding="utf-8")
except AttributeError:
    pass

from nafas.benchmark import SAFETY_CRITICAL, run_all, score  # noqa: E402

NAMES = {"crisis": "Emergency wording in notes (EN + AR)", "clinical": "Care-team flag (high residual AHI)",
         "qa": "Ask-your-data guardrails (routing + output checks)",
         "detect": "Lapse / decline / leak / leak-creep detectors", "barrier": "Barrier inference (top-1)"}


def main() -> None:
    results = run_all()
    s = score(results)
    lines = ["# Benchmark results", "",
             "Generated by `python scripts/benchmark.py`. Method and history: [BENCHMARK.md](BENCHMARK.md).", "",
             f"**{s['passed']} / {s['total']} cases pass** ({s['hard']} of them hard).", "",
             "| Suite | Safety-critical | Cases | Pass | Accuracy | Hard cases | Hard accuracy |",
             "|---|---|---|---|---|---|---|"]
    for k, v in s["suites"].items():
        lines.append(f"| {NAMES[k]} | {'yes' if k in SAFETY_CRITICAL else ''} | {v['cases']} | {v['passed']} | "
                     f"{v['accuracy']}% | {v['hard_cases']} | {v['hard_accuracy']}% |")
    c = s["suites"]["crisis"]
    lines += ["", f"Emergency wording: sensitivity **{c['sensitivity']}%** (every emergency phrasing caught), "
                  f"specificity **{c['specificity']}%** (near-misses that must not trigger).", "",
              "## Failures", ""]
    if s["failures"]:
        lines += ["| Case | Module | Expected | Actual | What |", "|---|---|---|---|---|"]
        for f in s["failures"]:
            lines.append(f"| {f['id']} | `{f['module']}` | {f['expected']} | {f['actual']} | {f['desc']} |")
    else:
        lines.append("None.")
    lines += ["", "## Every case", "", "| Case | Suite | Hard | Pass | What |", "|---|---|---|---|---|"]
    for r in results:
        lines.append(f"| {r.case.id} | {r.case.suite} | {'yes' if r.case.hard else ''} | "
                     f"{'✓' if r.ok else '✗ ' + str(r.module)} | {r.case.desc.replace('|', '/')} |")
    out = ROOT / "docs" / "BENCHMARK_RESULTS.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"{s['passed']}/{s['total']} cases pass ({s['hard']} hard)")
    for k, v in s["suites"].items():
        print(f"  {k:9s} {v['passed']:3d}/{v['cases']:<3d} {v['accuracy']:5}%   hard {v['hard_accuracy']}%")
    print(f"  crisis sensitivity {c['sensitivity']}%, specificity {c['specificity']}%")
    for f in s["failures"]:
        print(f"  FAIL {f['id']} [{f['module']}] {f['desc']}")
    print(f"→ {out}")


if __name__ == "__main__":
    main()
